// @ts-nocheck
import { describe, it, expect } from 'vitest';
import insightWeather from './insightWeather.json';
import { INSIGHT_SOLS, WEATHER_RANGE, coldFraction, outsideTemperatureC, solWeather } from './marsWeather.ts';
import { WEATHER_CONFIG } from '../config/constants.ts';

describe('InSight weather data (issue #108)', () => {
  it('was generated by the script with a source and a collection date, and no API key', () => {
    expect(insightWeather.source).toMatch(/InSight/);
    expect(insightWeather.fetched).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    expect(insightWeather.query).not.toMatch(/api_key/);
    expect(INSIGHT_SOLS.length).toBeGreaterThan(0);
  });

  it('game sol 1 uses the first real sol, then the next ones in order, wrapping around', () => {
    const n = INSIGHT_SOLS.length;
    expect(solWeather(0).sol).toBe(INSIGHT_SOLS[0].sol);
    expect(solWeather(23.9).sol).toBe(INSIGHT_SOLS[0].sol);
    expect(solWeather(24).sol).toBe(INSIGHT_SOLS[1].sol);
    expect(solWeather(n * 24 + 1).sol).toBe(INSIGHT_SOLS[0].sol);
    expect(solWeather(0).date).toMatch(/^\d{2}\/\d{2}\/\d{4}$/);
  });

  it('the outside air matches the real low before sunrise and the real high in the afternoon', () => {
    for (let i = 0; i < INSIGHT_SOLS.length; i++) {
      const base = i * 24;
      const { tempC } = INSIGHT_SOLS[i];
      expect(outsideTemperatureC(base + WEATHER_CONFIG.COLDEST_HOUR)).toBeCloseTo(tempC.min, 5);
      expect(outsideTemperatureC(base + WEATHER_CONFIG.WARMEST_HOUR)).toBeCloseTo(tempC.max, 5);
      // Nunca sai da faixa real do arquivo
      for (let h = 0; h < 24; h += 0.5) {
        const t = outsideTemperatureC(base + h);
        expect(t).toBeGreaterThanOrEqual(WEATHER_RANGE.coldestC - 1e-9);
        expect(t).toBeLessThanOrEqual(WEATHER_RANGE.warmestC + 1e-9);
      }
    }
  });

  it('changes through the sol and does not jump at midnight', () => {
    expect(outsideTemperatureC(5)).toBeLessThan(outsideTemperatureC(10));
    expect(outsideTemperatureC(20)).toBeLessThan(outsideTemperatureC(14));
    expect(Math.abs(outsideTemperatureC(23.999) - outsideTemperatureC(24))).toBeLessThan(0.1);
  });

  it('cold fraction is 0 at the warmest real air and 1 at the coldest', () => {
    expect(coldFraction(WEATHER_RANGE.warmestC)).toBe(0);
    expect(coldFraction(WEATHER_RANGE.coldestC)).toBe(1);
    expect(coldFraction(-60)).toBeGreaterThan(0);
    expect(coldFraction(-60)).toBeLessThan(1);
  });
});
